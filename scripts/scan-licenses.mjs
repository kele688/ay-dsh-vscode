/**
 * scan-licenses.mjs — 扫描生产依赖的 license 分布，生成 THIRD-PARTY-NOTICES.md。
 * 用法：node scripts/scan-licenses.mjs
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const modulesDir = join(root, "node_modules");
const outPath = join(root, "THIRD-PARTY-NOTICES.md");

/** 收集一个包目录的 license 信息。 */
function pkgInfo(dir, name) {
  const p = join(dir, "package.json");
  if (!existsSync(p)) return null;
  try {
    const m = JSON.parse(readFileSync(p, "utf8"));
    return { name: name || m.name || dir.split(/[\\/]/).pop(), version: m.version || "?", license: m.license || m.licenses || "UNKNOWN" };
  } catch {
    return { name: name || dir.split(/[\\/]/).pop(), version: "?", license: "UNKNOWN" };
  }
}

/** 递归扫描顶层作用域包（生产依赖闭包在顶层 node_modules 下）。 */
const results = new Map();
function scanScope(scopeDir) {
  for (const entry of readdirSync(scopeDir, { withFileTypes: true })) {
    const full = join(scopeDir, entry.name);
    if (entry.isDirectory()) {
      const info = pkgInfo(full);
      if (info) results.set(info.name, info);
    }
  }
}

// 顶层包
for (const entry of readdirSync(modulesDir, { withFileTypes: true })) {
  const full = join(modulesDir, entry.name);
  if (entry.isDirectory()) {
    if (entry.name.startsWith("@")) {
      scanScope(full);
    } else {
      const info = pkgInfo(full);
      if (info) results.set(info.name, info);
    }
  }
}

// 统计 license 分布
const byLicense = new Map();
for (const info of results.values()) {
  const lic = typeof info.license === "string" ? info.license : JSON.stringify(info.license);
  if (!byLicense.has(lic)) byLicense.set(lic, []);
  byLicense.get(lic).push(info);
}

const lines = [];
lines.push("# Third-Party Notices");
lines.push("");
lines.push(`This project bundles the following third-party packages (production dependency closure at build time, ${results.size} packages). All licenses are permissive open-source licenses compatible with redistribution under MIT.`);
lines.push("");
lines.push("Generated by `node scripts/scan-licenses.mjs`. Last generated: " + new Date().toISOString().slice(0, 10));
lines.push("");

for (const [lic, pkgs] of [...byLicense.entries()].sort((a, b) => b[1].length - a[1].length)) {
  lines.push(`## ${lic}`);
  lines.push("");
  lines.push(`> ${pkgs.length} package(s)`);
  lines.push("");
  for (const p of pkgs.sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(`- **${p.name}**@${p.version}`);
  }
  lines.push("");
}

lines.push("## Notes");
lines.push("");
lines.push("- Package licenses are read from each package's `package.json`; some packages declare multiple licenses or a license expression.");
lines.push("- `UNKNOWN` entries have no machine-readable license field; their source repositories generally carry permissive licenses — verify before commercial redistribution if strict compliance is required.");
lines.push("- The full license texts of the DeepSeek Harness packages (`@deepseek-ai/*`) are available in their respective packages under `node_modules/@deepseek-ai/*/LICENSE`.");

writeFileSync(outPath, lines.join("\n"), "utf8");
console.log(`已生成 ${outPath}（${results.size} 个包）`);
for (const [lic, pkgs] of byLicense.entries()) {
  console.log(`  ${lic}: ${pkgs.length} 个`);
}
